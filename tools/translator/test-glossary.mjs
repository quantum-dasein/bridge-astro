let ok = 0;
for (const [text, want] of cases) {
  const got = findTerms(text).map((t) => t.ru).sort();
  const pass = JSON.stringify(got) === JSON.stringify([...want].sort());
  ok += pass;
  console.log(pass ? 'OK  ' : 'FAIL', text, pass ? '' : '-> ' + JSON.stringify(got));
}

// Одно понятие — одна узбекская форма: дубли по ru недопустимы.
const dup = TERMS.map((t) => t.ru.toLowerCase()).filter((r, i, a) => a.indexOf(r) !== i);
const dupOk = dup.length === 0;
ok += dupOk;
console.log(dupOk ? 'OK  ' : 'FAIL', 'нет повторяющихся русских терминов', dupOk ? '' : dup.join(', '));

console.log(`${ok}/${cases.length + 1} | терминов: ${TERMS.length}`);
process.exit(ok === cases.length + 1 ? 0 : 1);
